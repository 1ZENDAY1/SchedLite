def create_tables(cur):
    cur.executescript("""
        DROP TABLE IF EXISTS schedule;
        DROP TABLE IF EXISTS classes;
        DROP TABLE IF EXISTS lesson_times;

        CREATE TABLE lesson_times (
            lesson_number INTEGER PRIMARY KEY,
            start_time    TEXT NOT NULL,
            end_time      TEXT NOT NULL
        );

        CREATE TABLE classes (
            class_name TEXT PRIMARY KEY,
            grade      TEXT NOT NULL
        );

        CREATE TABLE schedule (
            id            INTEGER PRIMARY KEY AUTOINCREMENT,
            class_name    TEXT    NOT NULL,
            day_of_week   TEXT    NOT NULL,
            lesson_number INTEGER NOT NULL,
            lesson        TEXT    NOT NULL,
            cabinet       TEXT    NOT NULL,
            UNIQUE (class_name, day_of_week, lesson_number),
            FOREIGN KEY (class_name)    REFERENCES classes(class_name),
            FOREIGN KEY (lesson_number) REFERENCES lesson_times(lesson_number)
        );
    """)


def fill_tables(cur):
    cur.executemany("INSERT INTO lesson_times VALUES (?, ?, ?)", LESSON_TIMES)
    cur.executemany("INSERT INTO classes (class_name, grade) VALUES (?, ?)", CLASSES)

    if SCHEDULE:
        cur.executemany(
            """INSERT INTO schedule
               (class_name, day_of_week, lesson_number, lesson, cabinet)
               VALUES (?, ?, ?, ?, ?)""",
            SCHEDULE,
        )


def main():
    print(f"Создаю базу: {DB_PATH}")
    conn = sqlite3.connect(DB_PATH)
    cur = conn.cursor()

    create_tables(cur)
    fill_tables(cur)
    conn.commit()

    n_times   = cur.execute("SELECT COUNT(*) FROM lesson_times").fetchone()[0]
    n_classes = cur.execute("SELECT COUNT(*) FROM classes").fetchone()[0]
    n_rows    = cur.execute("SELECT COUNT(*) FROM schedule").fetchone()[0]
    conn.close()

    print("Готово!")
    print(f"  Время уроков: {n_times}")
    print(f"  Классов:      {n_classes}")
    print(f"  Записей:      {n_rows}")
    if n_rows == 0:
        print("\n  Расписание пустое — заполни SCHEDULE и запусти заново.")


